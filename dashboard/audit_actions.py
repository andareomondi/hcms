"""
Audit action names.

Convention: RESOURCE_VERB, uppercase, verb in past tense for completed events.
Always use these constants. Never pass raw strings to the audit log.
"""


class AuditAction:
    # Accounts
    STAFF_REGISTERED = "STAFF_REGISTERED"
    PROFILE_UPDATED = "PROFILE_UPDATED"

    # Patients
    PATIENT_REGISTERED = "PATIENT_REGISTERED"
    PATIENT_UPDATED = "PATIENT_UPDATED"
    PATIENT_VIEWED = "PATIENT_VIEWED"
    PATIENT_ALLERGIES_VIEWED = "PATIENT_ALLERGIES_VIEWED"
    PATIENT_IDENTITY_CONFIRMED = "PATIENT_IDENTITY_CONFIRMED"

    # Triage and queue
    ENCOUNTER_OPENED = "ENCOUNTER_OPENED"
    CONSULTATION_COMPLETED = "CONSULTATION_COMPLETED"
    QUEUE_NEXT_PATIENT_CALLED = "QUEUE_NEXT_PATIENT_CALLED"

    # Clinical
    ENCOUNTER_RECORD_VIEWED = "ENCOUNTER_RECORD_VIEWED"
    CLINICAL_NOTE_SAVED = "CLINICAL_NOTE_SAVED"
    RADIOLOGY_REPORT_SAVED = "RADIOLOGY_REPORT_SAVED"

    # Pharmacy
    MEDICATION_CREATED = "MEDICATION_CREATED"
    MEDICATION_UPDATED = "MEDICATION_UPDATED"
    STOCK_ADJUSTED = "STOCK_ADJUSTED"
    MEDICATION_ADMINISTERED = "MEDICATION_ADMINISTERED"

    # Wards
    BED_ASSIGNED = "BED_ASSIGNED"
    PATIENT_DISCHARGED = "PATIENT_DISCHARGED"

    # Billing
    CHARGE_POSTED = "CHARGE_POSTED"
    CHARGE_PAID = "CHARGE_PAID"
